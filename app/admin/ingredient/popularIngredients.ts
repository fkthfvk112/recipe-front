/**
 * 로컬 캐시에서 질의어(query)와 일치하는 인기 식재료를 검색합니다.
 * 1) 정확 일치 단어 최우선
 * 2) 접두사 일치(Prefix Match: "양" -> "양파", "양배추"...) 우선
 * 3) 포함 일치(Contains Match: "버섯" -> "팽이버섯", "표고버섯"...) 차순위
 *
 * @param query 사용자가 입력한 식재료 검색어
 * @param maxResults 최대 반환 개수 (기본 8개)
 * @returns 매칭된 식재료 배열 (없으면 빈 배열)
 */
export function searchLocalPopularIngredients(
  query: string,
  maxResults = 8
): string[] {
  const trimmed = query.trim();
  if (!trimmed) return [];

  const exactMatches: string[] = [];
  const prefixMatches: string[] = [];
  const containsMatches: string[] = [];

  for (const item of POPULAR_INGREDIENTS) {
    if (item === trimmed) {
      exactMatches.push(item);
    } else if (item.startsWith(trimmed)) {
      prefixMatches.push(item);
    } else if (item.includes(trimmed)) {
      containsMatches.push(item);
    }
  }

  const combined = Array.from(
    new Set([...exactMatches, ...prefixMatches, ...containsMatches])
  );
  return combined.slice(0, maxResults);
}
